const spellDir = path.resolve("content/spells")
const folders = {
  0: "cantrips",
  1: "1st-level",
  2: "2nd-level",
  3: "3rd-level",
  4: "4th-level",
  5: "5th-level",
  6: "6th-level",
  7: "7th-level",
  8: "8th-level",
  9: "9th-level",
}
const slug = (s) =>
  s
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
for (const [title, level, school, classes, body] of spells) {
  const fileName = title === "Protection" ? "Protection.md" : `${title}.md`
  const file = path.join(spellDir, folders[level], fileName)
  const old = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : ""
  const match = old.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/)
  const previous = match ? (parse(match[1]) ?? {}) : {}
  const metadata = {
    ...previous,
    entity_type: "spell",
    canonical_id: previous.canonical_id || `spell.appendix-b.${slug(title)}`,
    title: title === "Protection" ? "Protection (Tamer Spell)" : title,
    spell_name: title,
    level,
    school,
    classes,
    source: "Appendix B — Spells",
    source_type: "third-party",
    edition: "system-neutral",
    adaptation: "curated",
    license_status: "reference-only",
    content_status: "complete",
  }
  delete metadata.incomplete_reason
  const suffix =
    level === 0
      ? "Cantrips"
      : `${level}${level === 1 ? "st" : level === 2 ? "nd" : level === 3 ? "rd" : "th"}-Level`
  const content = `---\n${stringify(metadata).trimEnd()}\n---\n\n${body}\n\n## Related Content\n\n**Spell Level:** [[spells/${folders[level]}|${suffix}]]\n\n**School:** ${school}\n\n**Source:** Appendix B — Spells\n\n**Available to:** ${classes.map((c) => `[[character-options/classes/${c}|${c}]]`).join(", ")}\n\n**Related:** [[spells|All Spells]] | [[character-options/classes/Tamer|Tamer]]\n`
  fs.writeFileSync(file, content)
}
